const { test, expect } = require('@playwright/test');

test.use({ serviceWorkers: 'block' });

test('opens the honors site directly with shared image assets and translated controls', async ({ page }, testInfo) => {
    const errors = [];
    const missing = [];
    const requests = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('response', response => { if (response.status() === 404) missing.push(response.url()); });
    page.on('request', request => requests.push(new URL(request.url()).pathname));
    await page.goto('/honors/');
    await expect(page.locator('body')).toHaveClass(/standalone-honors/);
    await expect(page.locator('[data-honor-image]')).toHaveCount(35);
    const folder = page.locator('[data-project-folder-window]');
    await expect(folder).toBeVisible();
    await expect(page.locator('[data-project-folder-root]')).toBeHidden();
    await expect(page.locator('[data-project-folder-back]')).toBeHidden();
    await expect(page.locator('[data-open-honors]')).toBeHidden();
    await expect(page.locator('[data-sync-window], [data-gomoku-window], [data-app-window]')).toHaveCount(0);
    await expect(page.locator('[data-project-folder-search]')).toHaveAttribute('placeholder', '搜索');
    const first = page.locator('[data-honor-image]').first();
    await expect(first).toContainText('2025 美国大学生数学建模');
    await expect.poll(() => first.locator('img').evaluate(image => image.naturalWidth)).toBeGreaterThan(0);
    const bounds = await folder.boundingBox();
    expect(bounds.x).toBeGreaterThanOrEqual(0);
    expect(bounds.y).toBeGreaterThanOrEqual(0);
    expect(bounds.width).toBeGreaterThanOrEqual(page.viewportSize().width - 12);
    expect(bounds.x + bounds.width).toBeLessThanOrEqual(page.viewportSize().width);
    expect(bounds.y + bounds.height).toBeLessThanOrEqual(page.viewportSize().height);
    for (const [menu, action] of [['folder-file', 'folder-open'], ['folder-view', 'folder-refresh']]) {
        await page.locator(`[data-window-menu="${menu}"]`).focus();
        await page.keyboard.press('ArrowUp');
        await expect(page.locator(`[data-menu-action="${action}"]`)).toBeFocused();
        await page.keyboard.press('ArrowDown');
        await expect(page.locator(`[data-menu-action="${action}"]`)).toBeFocused();
        await page.keyboard.press('Escape');
    }
    await page.locator('[data-taskbar-lang]').click();
    await expect(page.locator('html')).toHaveAttribute('lang', 'en');
    await expect(page.locator('[data-project-folder-search]')).toHaveAttribute('placeholder', 'Search');
    await expect(first).toContainText('2025 MCM Meritorious Winner');
    await page.locator('[data-taskbar-lang]').click();
    await expect(first).toContainText('2025 美国大学生数学建模');
    await page.screenshot({ path: testInfo.outputPath('honors-site.png') });
    expect(requests).toContain('/portfolio/assets/honors/certificates.json');
    expect(requests.some(path => /^\/honors\/assets\//.test(path))).toBe(false);
    expect(requests.some(path => /\/portfolio\/js\/(main|chat|gomoku-game|gomoku-engine)\.js$|\/bundle\.|\/immersive\./.test(path))).toBe(false);
    expect(missing).toEqual([]);
    expect(errors).toEqual([]);
});

test('reuses filtered photo preview, zoom and session recovery on the honors site', async ({ page }) => {
    await page.goto('/honors/');
    await expect(page.locator('[data-honor-image]')).toHaveCount(35);
    const search = page.locator('[data-project-folder-search]');
    await search.fill('APMCM');
    await expect(page.locator('[data-honor-image]:visible')).toHaveCount(1);
    await search.fill('数学建模');
    expect(await page.locator('[data-honor-image]:visible').count()).toBeGreaterThan(1);
    await search.fill('RoboMaster');
    const matching = page.locator('[data-honor-image]:visible');
    const count = await matching.count();
    expect(count).toBeGreaterThan(1);
    const firstSource = await matching.first().getAttribute('data-image-src');
    const secondSource = await matching.nth(1).getAttribute('data-image-src');
    await matching.first().click();
    const image = page.locator('[data-image-preview-image]');
    await expect(page.locator('[data-image-preview-window]')).toBeVisible();
    await expect(image).toHaveAttribute('src', firstSource);
    await expect.poll(() => image.evaluate(element => element.naturalWidth)).toBeGreaterThan(0);
    await expect(page.locator('[data-image-counter]')).toHaveText(`1 / ${count}`);
    const folder = page.locator('[data-project-folder-window]');
    const preview = page.locator('[data-image-preview-window]');
    const folderTask = page.locator('[data-project-folder-task]');
    await folderTask.click();
    await expect(folder).toHaveClass(/is-active/);
    await expect(matching.first()).toBeFocused();
    await expect(preview).toBeVisible();
    await folderTask.click();
    await expect(folder).toBeVisible();
    await expect(matching.first()).toBeFocused();
    await page.locator('[data-image-preview-task]').click();
    await expect(preview).toHaveClass(/is-active/);
    await expect(page.locator('[data-image-preview-action="close"]')).toBeFocused();
    await page.locator('[data-image-preview-toolbar] [data-preview-zoom-in]').click();
    await expect(page.locator('[data-image-preview-toolbar] [data-preview-zoom-value]')).toHaveText('125%');
    await page.locator('[data-image-next]').click();
    await expect(image).toHaveAttribute('src', secondSource);
    await expect(page.locator('[data-image-counter]')).toHaveText(`2 / ${count}`);
    await page.reload();
    await expect(search).toHaveValue('RoboMaster');
    await expect(page.locator('[data-image-preview-window]')).toBeVisible();
    await expect(image).toHaveAttribute('src', secondSource);
    await expect(page.locator('[data-image-counter]')).toHaveText(`2 / ${count}`);
    await page.locator('[data-image-previous]').click();
    await expect(image).toHaveAttribute('src', firstSource);
    await page.locator('[data-taskbar-lang]').click();
    await expect(page.locator('[data-image-previous]')).toHaveAttribute('aria-label', 'Previous image');
    await expect(page.locator('[data-image-counter]')).toHaveText(`1 / ${count}`);
    await page.locator('[data-image-preview-action="close"]').click();
    await expect(page.locator('[data-project-folder-window]')).toBeVisible();
    await expect(matching).toHaveCount(count);
});

test('opens honors from the desktop in a new tab without replacing or overwriting desktop state', async ({ page }) => {
    await page.goto('/portfolio/');
    if (await page.locator('[data-window-action="minimize"]').isVisible()) await page.locator('[data-window-action="minimize"]').click();
    await page.locator('.desktop-shortcut[data-open-project-folder]').click();
    const link = page.locator('[data-open-honors]');
    await expect(link).toBeHidden();
    await page.locator('[data-folder="honors"]').click();
    await expect(page.locator('[data-honor-image]')).toHaveCount(35);
    await expect(link).toBeVisible();
    await expect(link).toHaveAttribute('href', '/honors/');
    await expect(link).toHaveAttribute('target', '_blank');
    const popupPromise = page.waitForEvent('popup');
    await link.click();
    const popup = await popupPromise;
    await expect(popup).toHaveURL(/\/honors\/$/);
    await expect(popup.locator('[data-honor-image]')).toHaveCount(35);
    await expect(page).toHaveURL(/\/portfolio\/$/);
    await expect(page.locator('[data-honors-folder-view]')).toBeVisible();
    await popup.close();
    await page.locator('[data-project-folder-search]').fill('APMCM');
    await page.evaluate(() => window.dispatchEvent(new Event('gavin:save-session-state')));
    const desktopState = await page.evaluate(() => sessionStorage.getItem('gavin-portfolio-desktop-session'));
    expect(desktopState).not.toBeNull();
    await page.goto('/honors/');
    await expect(page.locator('[data-honor-image]')).toHaveCount(35);
    await page.locator('[data-project-folder-search]').fill('RoboMaster');
    await page.evaluate(() => window.dispatchEvent(new Event('gavin:save-session-state')));
    expect(await page.evaluate(() => sessionStorage.getItem('gavin-portfolio-desktop-session'))).toBe(desktopState);
    await page.goto('/portfolio/');
    await expect(page.locator('[data-project-folder-search]')).toHaveValue('APMCM');
    await expect(page.locator('[data-honor-image]:visible')).toHaveCount(1);
});
